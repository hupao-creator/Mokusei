"""Generate the native emoji allowlist from the runtime's pinned Unicode data."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "internal/services/taglabel"
license_text = (source / "UNICODE-LICENSE.txt").read_text()
sequences = (source / "emoji.txt").read_text().splitlines()
assert all(value and not any(c in value for c in ['"', '\\', ' ']) for value in sequences)
output = "// Generated by scripts/generate-tag-emoji.py; do not edit.\n"
output += "/*\n" + license_text + "*/\n"
output += 'enum SemanticTagEmojiData {\n    static let sequences = """\n'
output += "\n".join("    " + value for value in sequences)
output += '\n    """\n}\n'
target = root / "app/macos/Sources/Shared/PluginAPI/SemanticTagEmojiData.swift"
target.write_text(output)
