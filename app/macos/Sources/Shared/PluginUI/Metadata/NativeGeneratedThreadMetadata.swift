/// Matches the renderer's ^\p{RGI_Emoji}$ / v property without depending on
/// the operating system's Unicode release or treating a bare digit as emoji.
public func nativeGeneratedThreadEmoji(metadata: JSONValue?) -> String? {
    guard metadata?["kind"]?.stringValue == "generated-thread-metadata",
          case .string(let emoji) = metadata?["emoji"], NativeRGIEmoji.values.contains(emoji) else { return nil }
    return emoji.string
}

/// Expand only a catalog title copied by the generated-metadata policy. The
/// owning Harness supplies its prompt; presentation never guesses an intent.
public func nativeGeneratedThreadDocumentTitle(metadata: JSONValue?, title: JSONText,
                                               initialPrompt: JSONText?) -> String {
    guard metadata?["kind"]?.stringValue == "generated-thread-metadata",
          metadata?["title"] == .string(title), title.codeUnits.last == 0x2026,
          let initialPrompt, !initialPrompt.codeUnits.isEmpty else { return title.string }
    let prompt = nativeNormalizedPromptTitle(initialPrompt)
    var copied = prompt.codeUnits
    if copied.count > 34 {
        var index = 0
        while index < copied.count {
            let width = (0xD800...0xDBFF).contains(copied[index]) && index + 1 < copied.count &&
                (0xDC00...0xDFFF).contains(copied[index + 1]) ? 2 : 1
            if index + width > 33 { break }
            index += width
        }
        copied = Array(copied.prefix(index))
        while copied.last == 32 { copied.removeLast() }
        copied.append(0x2026)
    }
    guard JSONText(codeUnits: copied) == title else { return title.string }
    if prompt.codeUnits.count <= 1_024 { return prompt.string }
    var result = Array(prompt.codeUnits.prefix(1_023))
    if let last = result.last, (0xD800...0xDBFF).contains(last) { result.removeLast() }
    while result.last == 32 { result.removeLast() }
    result.append(0x2026)
    return JSONText(codeUnits: result).string
}

public func nativeGeneratedThreadDocumentTitle(metadata: JSONValue?, title: String,
                                               initialPrompt: String?) -> String {
    nativeGeneratedThreadDocumentTitle(metadata: metadata, title: JSONText(title), initialPrompt: initialPrompt.map { JSONText($0) })
}

private func nativeNormalizedPromptTitle(_ prompt: JSONText) -> JSONText {
    var result: [UInt16] = []
    var spacePending = false
    for unit in prompt.codeUnits {
        let space: Bool
        switch unit {
        case 0...32, 127, 0x00A0, 0x1680, 0x2000...0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0xFEFF: space = true
        default: space = false
        }
        if space { spacePending = !result.isEmpty }
        else {
            if spacePending { result.append(32) }
            result.append(unit); spacePending = false
        }
    }
    return JSONText(codeUnits: result)
}

